<h1>Guide</h1>
<p class="subtitle">
	Budgetix prévoit vos comptes jusqu'à la fin du mois à partir de vos revenus, dépenses et virements
	récurrents. Suivez les étapes dans l'ordre pour bien démarrer.
</p>

<section class="card">
	<h2>1. Créez vos comptes</h2>
	<p>
		Dans <a href="/accounts">Comptes</a>, ajoutez chaque compte bancaire :
		<strong>personnel</strong>,
		<strong>épargne</strong> ou <strong>commun</strong>.
	</p>
	<ul>
		<li>
			<strong>Solde initial</strong> : le solde du compte en début de mois, avant tout mouvement.
		</li>
		<li>
			<strong>Solde actuel</strong> (optionnel) : le solde réel lu sur votre banque. S'il est saisi, la
			prévision part de ce montant et le tableau de bord affiche l'écart avec le solde attendu.
		</li>
	</ul>
</section>

<section class="card">
	<h2>2. Ajoutez vos revenus</h2>
	<p>
		Dans <a href="/incomes">Revenus</a>, saisissez vos entrées d'argent mensuelles (salaire, loyer
		perçu…) avec le jour du mois où elles arrivent. Un revenu est compté dès que son jour est passé.
	</p>
</section>

<section class="card">
	<h2>3. Ajoutez vos dépenses</h2>
	<p>
		Dans <a href="/expenses">Dépenses</a>, saisissez vos prélèvements mensuels et leur jour. Chaque
		mois, cochez <strong>Réalisée</strong> (○ → ✓) quand une dépense est passée sur votre compte : tant
		qu'elle n'est pas cochée, elle reste à venir dans la prévision, même si son jour est passé.
	</p>
	<p>
		Une dépense <strong>partagée</strong> est répartie entre plusieurs utilisateurs liés, soit avec
		des parts fixes en %, soit <strong>au prorata</strong> des revenus personnels de chacun.
	</p>
</section>

<section class="card">
	<h2>4. Planifiez vos virements</h2>
	<p>
		Dans <a href="/transfers">Virements</a>, indiquez les virements récurrents entre vos comptes
		(vers l'épargne, vers le compte commun…). Ils sont débités d'un compte et crédités sur l'autre à
		leur jour du mois.
	</p>
</section>

<section class="card">
	<h2>5. Partagez avec un proche (optionnel)</h2>
	<p>
		Dans <a href="/links">Liaisons</a>, envoyez une demande à un autre utilisateur par e-mail. Une
		fois acceptée, vous pouvez partager un compte avec lui depuis <a href="/accounts">Comptes</a>
		(bouton
		<strong>Partager</strong>) et répartir des dépenses entre vous.
	</p>
</section>

<section class="card">
	<h2>6. Lisez le tableau de bord</h2>
	<p>Le <a href="/dashboard">Tableau de bord</a> résume le mois en cours :</p>
	<ul>
		<li>
			<strong>Reste prévu en fin de mois</strong> : le total de vos comptes une fois tous les mouvements
			du mois passés. Un avertissement s'affiche si un compte risque d'être à découvert.
		</li>
		<li>
			<strong>Marge mensuelle</strong> : revenus et virements entrants moins dépenses et virements sortants,
			par compte.
		</li>
		<li>
			<strong>Équilibrage</strong> : pour chaque compte commun, le montant que chacun doit y virer pour
			couvrir sa part des dépenses.
		</li>
	</ul>
</section>

